"""Render extracted items into static HTML pages and per-project data files.

Everything taken from a log is escaped. Jinja2 autoescapes every value, and Markdown is
rendered by markdown-it-py with raw HTML disabled; rendered Markdown is the only value a
template marks safe. Pages load nothing but local files (see `CSP`). The renderer does
no file I/O except reading its own templates and assets.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import datetime, timezone
from importlib import resources
from typing import Any

from jinja2 import Environment, PackageLoader, StrictUndefined
from markdown_it import MarkdownIt
from markdown_it.common.utils import escapeHtml
from markdown_it.token import Token

from session_doc.extractor import Item

# Scripts and styles may come from local files only; nothing else may load. `file:` is
# listed because browsers disagree on whether `'self'` matches other file:// URLs, and
# `'self'` keeps the pages working when they are served over http. All scripts are
# external files, so no 'unsafe-inline' is needed. See docs/DECISIONS.md.
CSP = (
    "default-src 'none'; script-src 'self' file:; style-src 'self' file:; "
    "base-uri 'none'; form-action 'none'"
)

KINDS = ("prompt", "deliverable", "decision", "status")

# Links in rendered Markdown stay clickable only for these schemes. Everything else,
# including relative paths, javascript:, data:, and file:, is left as plain text.
LINK_SCHEMES = ("http:", "https:", "mailto:")

ASSETS = ("style.css", "app.js", "minisearch.min.js", "minisearch.LICENSE.txt")

# Per-project data file (`search-index.js`): session list for the sidebar and search docs.
DATA_FORMAT = 1
DATA_PREFIX = "/* Generated by session-doc. Do not edit. */\nwindow.sessionDocData = "
DATA_SUFFIX = ";\n"


# --------------------------------------------------------------------------- view models


@dataclass(frozen=True)
class ProjectInfo:
    slug: str
    name: str
    cwd: str


@dataclass(frozen=True)
class SessionInfo:
    slug: str
    title: str
    start: datetime | None
    end: datetime | None
    branch: str | None
    counts: Mapping[str, int]
    skipped_lines: int = 0

    @property
    def item_count(self) -> int:
        return sum(self.counts.values())


@dataclass(frozen=True)
class _ItemView:
    anchor: str
    kind: str
    inferred: bool
    title: str
    iso: str
    when: str
    clock: str
    html: str


@dataclass(frozen=True)
class _ProjectRow:
    slug: str
    name: str
    cwd: str
    sessions: int
    items: int
    last: datetime | None


# --------------------------------------------------------------------------- markdown


def _validate_link(url: str) -> bool:
    return url.strip().lower().startswith(LINK_SCHEMES)


def _render_link_open(self: Any, tokens: list[Token], idx: int, options: Any, env: Any) -> str:
    tokens[idx].attrSet("rel", "noopener noreferrer")
    return self.renderToken(tokens, idx, options, env)


def _render_image(self: Any, tokens: list[Token], idx: int, options: Any, env: Any) -> str:
    """Never load an image: render a plain link to it instead."""
    token = tokens[idx]
    src = str(token.attrGet("src") or "")
    alt = self.renderInlineAsText(token.children or [], options, env)
    label = f"image: {alt}" if alt else "image"
    return f'<a href="{escapeHtml(src)}" rel="noopener noreferrer">{escapeHtml(label)}</a>'


def _make_markdown(*, breaks: bool) -> MarkdownIt:
    # "js-default" is CommonMark plus tables and strikethrough, with html=False.
    md = MarkdownIt("js-default", {"breaks": breaks})
    md.validateLink = _validate_link  # type: ignore[method-assign]
    md.add_render_rule("link_open", _render_link_open)
    md.add_render_rule("image", _render_image)
    return md


_MD = _make_markdown(breaks=False)
_MD_BREAKS = _make_markdown(breaks=True)


def _align_classes(tokens: list[Token]) -> None:
    """Replace table alignment `style` attributes (blocked by the CSP) with classes."""
    for token in tokens:
        if token.type in ("th_open", "td_open"):
            style = token.attrGet("style")
            if isinstance(style, str) and style.startswith("text-align:"):
                del token.attrs["style"]
                token.attrSet("class", "align-" + style.split(":", 1)[1].strip())


def render_markdown(text: str, *, breaks: bool = False) -> str:
    """Render Markdown to HTML. Raw HTML in `text` comes out escaped, never as markup.

    With `breaks`, single line breaks are kept (for text people typed, and commit messages).
    """
    md = _MD_BREAKS if breaks else _MD
    tokens = md.parse(text)
    _align_classes(tokens)
    return md.renderer.render(tokens, md.options, {})


def item_html(item: Item) -> str:
    """Agent-written deliverables are Markdown documents; other items keep line breaks."""
    return render_markdown(item.body, breaks=item.kind != "deliverable")


# --------------------------------------------------------------------------- formatting


def format_time(ts: datetime | None, fmt: str = "%Y-%m-%d %H:%M") -> str:
    """Local time of the machine running session-doc."""
    if ts is None:
        return ""
    try:
        return ts.astimezone().strftime(fmt)
    except (OverflowError, OSError, ValueError):
        return ts.strftime(fmt)


def iso_utc(ts: datetime | None) -> str:
    return ts.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ") if ts else ""


def anchor(index: int) -> str:
    """Fragment id of the item at `index` (0-based) on its session page."""
    return f"item-{index + 1}"


# --------------------------------------------------------------------------- pages

_env = Environment(
    loader=PackageLoader("session_doc", "templates"),
    autoescape=True,
    undefined=StrictUndefined,
    trim_blocks=True,
    lstrip_blocks=True,
    keep_trailing_newline=True,
)
_env.filters["when"] = format_time
_env.filters["iso"] = iso_utc
_env.globals["csp"] = CSP
_env.globals["kinds"] = KINDS


def _item_views(items: Sequence[Item]) -> list[_ItemView]:
    days = {format_time(i.timestamp, "%Y-%m-%d") for i in items if i.timestamp}
    clock_fmt = "%m-%d %H:%M" if len(days) > 1 else "%H:%M"
    return [
        _ItemView(
            anchor=anchor(n),
            kind=item.kind,
            inferred=item.confidence == "inferred",
            title=item.title,
            iso=iso_utc(item.timestamp),
            when=format_time(item.timestamp),
            clock=format_time(item.timestamp, clock_fmt),
            html=item_html(item),
        )
        for n, item in enumerate(items)
    ]


def render_session_page(project: ProjectInfo, session: SessionInfo, items: Sequence[Item]) -> str:
    """`projects/<project>/sessions/<session>.html`."""
    return _env.get_template("session.html").render(
        root="../../../",
        project_index="../index.html",
        data_src="../search-index.js",
        project=project,
        session=session,
        items=_item_views(items),
    )


def render_project_page(project: ProjectInfo, sessions: Sequence[SessionInfo]) -> str:
    """`projects/<project>/index.html`. `sessions` are listed in the order given."""
    return _env.get_template("project.html").render(
        root="../../",
        project_index="index.html",
        data_src="search-index.js",
        project=project,
        sessions=sessions,
    )


def render_index_page(projects: Sequence[tuple[ProjectInfo, Sequence[SessionInfo]]]) -> str:
    """Top-level `index.html`: one row per project, most recently active first."""
    rows = []
    for project, sessions in projects:
        stamps = [t for s in sessions for t in (s.end, s.start) if t]
        rows.append(
            _ProjectRow(
                slug=project.slug,
                name=project.name,
                cwd=project.cwd,
                sessions=len(sessions),
                items=sum(s.item_count for s in sessions),
                last=max(stamps, default=None),
            )
        )
    epoch = datetime.min.replace(tzinfo=timezone.utc)
    rows.sort(key=lambda r: (r.last or epoch, r.name), reverse=True)
    return _env.get_template("index.html").render(root="", projects=rows)


# --------------------------------------------------------------------------- data file


def search_docs(session_slug: str, items: Sequence[Item]) -> list[dict[str, Any]]:
    """Search documents for one session, in the shape `app.js` indexes."""
    return [
        {
            "id": f"{session_slug}/{anchor(n)}",
            "session": session_slug,
            "anchor": anchor(n),
            "kind": item.kind,
            "inferred": item.confidence == "inferred",
            "title": item.title,
            "text": item.body,
        }
        for n, item in enumerate(items)
    ]


def project_data_js(
    project: ProjectInfo, sessions: Sequence[SessionInfo], docs: Sequence[Mapping[str, Any]]
) -> str:
    """The per-project `search-index.js`, loaded with a script tag (works from file://)."""
    payload = {
        "format": DATA_FORMAT,
        "project": {"slug": project.slug, "name": project.name, "cwd": project.cwd},
        "sessions": [
            {"slug": s.slug, "title": s.title, "date": format_time(s.start), "items": s.item_count}
            for s in sessions
        ],
        "docs": list(docs),
    }
    text = json.dumps(payload, ensure_ascii=True, separators=(",", ":"))
    # `<`, `>`, and `&` only occur inside JSON strings, where these escapes are equivalent.
    text = text.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    return DATA_PREFIX + text + DATA_SUFFIX


def read_project_docs(text: str) -> dict[str, list[dict[str, Any]]] | None:
    """Search docs per session slug from a data file written by `project_data_js`.

    Returns None if the text is not such a file, so the caller can rebuild it.
    """
    if not (text.startswith(DATA_PREFIX) and text.endswith(DATA_SUFFIX)):
        return None
    try:
        payload = json.loads(text[len(DATA_PREFIX) : -len(DATA_SUFFIX)])
    except ValueError:
        return None
    if not isinstance(payload, dict) or payload.get("format") != DATA_FORMAT:
        return None
    docs = payload.get("docs")
    if not isinstance(docs, list):
        return None
    found: dict[str, list[dict[str, Any]]] = {}
    for doc in docs:
        if isinstance(doc, dict) and isinstance(doc.get("session"), str):
            found.setdefault(doc["session"], []).append(doc)
    return found


def asset_files() -> dict[str, bytes]:
    """Shared files for `assets/`: stylesheet, viewer script, and vendored MiniSearch."""
    base = resources.files("session_doc") / "assets"
    return {name: (base / name).read_bytes() for name in ASSETS}
